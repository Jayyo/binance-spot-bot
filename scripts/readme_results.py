"""Regenerate the backtest numbers and charts shown in the README.

    python scripts/readme_results.py

Downloads 3 symbols x 49 monthly 1h archives (about 10 MB) into data/, checks
them against docs/results/manifest.json, runs every combination below and
writes docs/results/results.md plus the charts in docs/img/. The experiment
(symbols, period, parameters, costs) was fixed before the first run and is not
tuned on its output.
"""

from __future__ import annotations

import argparse
import sys
from decimal import Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from spotbot import backtest, data, report  # noqa: E402
from spotbot.metrics import yearly_returns  # noqa: E402
from spotbot.strategy import RsiParams  # noqa: E402

SYMBOLS = ["BTCUSDT", "ETHUSDT", "SOLUSDT"]
VARIANTS = [("RSI", RsiParams()), ("RSI + EMA200", RsiParams(trend_ema=200))]
COSTS = [("costs", Decimal(10), Decimal(5)), ("no costs", Decimal(0), Decimal(0))]
START, END, WARMUP_FROM = "2022-01", "2025-12", "2021-12"
MANIFEST = ROOT / "docs" / "results" / "manifest.json"


def pct(x: float) -> str:
    return f"{x * 100:+.1f}%"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data-dir", type=Path, default=ROOT / "data")
    ap.add_argument("--pin", action="store_true", help="write the manifest instead of checking it")
    args = ap.parse_args()

    datasets = {s: data.load(s, "1h", WARMUP_FROM, END, args.data_dir) for s in SYMBOLS}
    if args.pin:
        data.write_manifest(list(datasets.values()), MANIFEST)
    data.verify_manifest(list(datasets.values()), MANIFEST)

    rows, gross, hero = [], {}, None
    for symbol in SYMBOLS:
        for label, params in VARIANTS:
            for cost_label, fee, slip in COSTS:
                cfg = backtest.BacktestConfig(
                    symbol, "1h", START, END, params=params, fee_bps=fee, slippage_bps=slip
                )
                res = backtest.run(cfg, datasets[symbol])
                if cost_label == "no costs":
                    gross[(symbol, label)] = res.summary.total_return
                    continue
                rows.append((symbol, label, res))
                if symbol == "BTCUSDT" and label == "RSI":
                    hero = res

    lines = [
        "| Symbol | Rules | Return | Before costs | Max drawdown | Trades | Bars in market | Buy & hold | B&H max drawdown |",
        "|---|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for symbol, label, res in rows:
        s, h = res.summary, res.hold
        lines.append(
            f"| {symbol} | {label} | {pct(s.total_return)} | {pct(gross[(symbol, label)])} | "
            f"{pct(-s.max_drawdown)} | {s.trades} | {s.exposure:.0%} | {pct(h.total_return)} | {pct(-h.max_drawdown)} |"
        )
    table = "\n".join(lines)

    years = sorted({y for _, _, r in rows for y in yearly_returns(r.points)})
    ylines = [
        "| Symbol | Rules | " + " | ".join(map(str, years)) + " |",
        "|---|---|" + "---:|" * len(years),
    ]
    for symbol, label, res in rows:
        yr = yearly_returns(res.points)
        ylines.append(f"| {symbol} | {label} | " + " | ".join(pct(yr[y]) for y in years) + " |")
    for symbol in SYMBOLS:
        res = next(r for s, _, r in rows if s == symbol)
        yr = yearly_returns(res.hold_points)
        ylines.append(f"| {symbol} | buy & hold | " + " | ".join(pct(yr[y]) for y in years) + " |")

    out = ROOT / "docs" / "results" / "results.md"
    out.write_text(
        "# Backtest results\n\n"
        "Generated by `python scripts/readme_results.py`. Every number below comes from one run of that script.\n\n"
        "## Conditions\n\n"
        + "\n".join(
            f"- {k}: {v}" for k, v in report.conditions(hero) if k not in ("Missing bars", "Period")
        )
        + f"\n- Period: {START} to {END} (UTC), 1h bars, warm-up from {WARMUP_FROM}"
        + "\n- Missing bars: "
        + ("; ".join(hero.data.gap_lines()) or "none")
        + "\n- Symbols: BTCUSDT, ETHUSDT, SOLUSDT, picked as large and liquid, not as a market sample; "
        "all three survived and are correlated."
        + '\n- "Before costs" reruns the same rules with zero fee and slippage.\n\n'
        "## Summary\n\n"
        + table
        + "\n\n## By calendar year (with costs)\n\n"
        + "\n".join(ylines)
        + "\n"
    )
    img = ROOT / "docs" / "img"
    img.mkdir(parents=True, exist_ok=True)
    report.plot(hero, img / "btcusdt-equity.png", width=11.0, height=6.6, dpi=100)
    window = report.find_window(hero, days=6)
    report.plot_zoom(hero, *window, img / "btcusdt-trades.png")
    print(table)
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
